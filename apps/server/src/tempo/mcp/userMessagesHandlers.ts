import * as Effect from "effect/Effect";

import * as McpInvocationContext from "../../mcp/McpInvocationContext.ts";
import * as McpToolAccess from "../../mcp/McpToolAccess.ts";
import * as OrchestratorMcpService from "../../mcp/OrchestratorMcpService.ts";
import { TempoUserMessagesToolkit } from "./userMessagesTools.ts";

export const layer = McpToolAccess.toLayer(TempoUserMessagesToolkit, {
  t3_user_messages: McpToolAccess.reads((input) =>
    Effect.gen(function* () {
      const scope = yield* McpInvocationContext.McpInvocationContext;
      const service = yield* OrchestratorMcpService.OrchestratorMcpService;
      return yield* service.readUserMessages(scope, input);
    }),
  ),
});
